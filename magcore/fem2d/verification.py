# ПРАВДОПОДОБИЕ КОНСТРУКЦИИ И РЕЖИМА (добавлено 2026-09-08 по итогам аудита)
#
# Зачем. Аудит 2026-09-03 показал, что расчёт молча шёл в физически невозможном режиме:
# плотность тока 33,4 А/мм² была подписана как «номинальная», а обмотка не позволяла
# машине раскрутиться до заявленных 7000 об/мин ни при какой модуляции. Ни одна проверка
# этого не ловила. Эти пять проверок закрывают дыру.
#
# ИСТОЧНИК НОРМ: Pyrhönen J., Jokinen T., Hrabovcová V. "Design of Rotating Electrical
# Machines", 2-е изд., Wiley, 2014 — табл. 6.3 (с. 298), табл. 6.4 (с. 299), ур. (7.17)
# и пример 7.3 (с. 338). Для машин с ПМ:
#     J = 4…6,5 А/мм²   (а для ЗУБЦОВЫХ КАТУШЕК книга предписывает строку полюсной
#                        обмотки: 2…5,5 — прямое указание в тексте после табл. 6.3);
#     A = 35…65 кА/м;   σ_тан = 21 / 33,5 / 48 кПа (мин / средн. / макс);
#     AJ = 14…42,25·10¹⁰ А²/м³ (для воздушного охлаждения вообще 10…35·10¹⁰).
# Потолок ЛЮБОГО длительного режима во всей монографии — 13…18 А/мм², и это обмотка с
# ПРЯМЫМ ВОДЯНЫМ охлаждением проводника изнутри.
#
# ⚠ ЧЕСТНО О РАЗБРОСЕ. Таблицы составлены для ЗАКРЫТЫХ промышленных машин в режиме S1.
# Открытый обдуваемый аутраннер БПЛА с изоляцией класса H живёт выше: инженерная практика
# даёт 12…17 А/мм² длительно. Расхождение реально и не усредняется — поэтому ГЛАВНЫМ
# (книжным) критерием здесь взят AJ, а полоса по J выдаётся справочно и помечена как
# практика. В паспортах БПЛА-моторов «max continuous» нередко означает 180 с, а не S1.

#: Полосы плотности тока [А/мм², СКЗ в меди] по режимам — ИНЖЕНЕРНАЯ ПРАКТИКА, не ГОСТ.
CURRENT_DENSITY_BANDS = {"continuous": (0.0, 15.0), "overload": (0.0, 24.0),
                         "peak": (0.0, 35.0)}
#: Тепловая нагрузка AJ [А²/м³] — верхняя граница длительного режима (Pyrhönen, пример 7.3).
AJ_LIMIT_CONTINUOUS = 42.25e10
#: Касательное напряжение [Па] для машин с ПМ (Pyrhönen, табл. 6.4): мин / средн. / макс.
TANGENTIAL_STRESS_PM = (21.0e3, 33.5e3, 48.0e3)


def check_current_density(j_rms_a_per_mm2: float, regime: str = "continuous") -> Check:
    """Плотность тока в меди против полосы режима. `regime`: continuous|overload|peak."""
    if regime not in CURRENT_DENSITY_BANDS:
        return Check("Плотность тока", SKIP, "неизвестный режим %r" % regime)
    lo, hi = CURRENT_DENSITY_BANDS[regime]
    j = float(j_rms_a_per_mm2)
    if lo <= j <= hi:
        return Check("Плотность тока", PASS, "%.1f А/мм² (режим «%s», до %.0f)" % (j, regime, hi))
    return Check("Плотность тока", FAIL,
                 "%.1f А/мм² при пределе %.0f для режима «%s»" % (j, hi, regime),
                 "Либо снизить ток, либо переименовать режим: %.1f А/мм² — это не "
                 "длительная нагрузка. Книжная норма для машин с ПМ 4–6,5 (зубцовые "
                 "катушки 2–5,5); практика обдуваемого аутраннера 12–17 длительно." % j)


def check_thermal_loading(linear_current_a_per_m: float, j_rms_a_per_m2: float) -> Check:
    """
    ГЛАВНЫЙ книжный критерий длительного режима: произведение AJ не зависит от размера
    машины и определяется только эффективностью охлаждения (Pyrhönen, ур. 7.17).
    """
    aj = float(linear_current_a_per_m) * float(j_rms_a_per_m2)
    ratio = aj / AJ_LIMIT_CONTINUOUS
    if ratio <= 1.0:
        return Check("Тепловая нагрузка AJ", PASS,
                     "%.2g А²/м³ = %.2f от предела длительного режима" % (aj, ratio))
    return Check("Тепловая нагрузка AJ", FAIL,
                 "%.2g А²/м³ — превышение в %.1f раза над длительным пределом %.2g"
                 % (aj, ratio, AJ_LIMIT_CONTINUOUS),
                 "Режим кратковременный. Допустимая длительность ~ обратно квадрату "
                 "превышения; объявлять его номинальным нельзя.")


def check_tangential_stress(sigma_pa: float) -> Check:
    """
    Касательное напряжение в зазоре против табл. 6.4 (машины с ПМ): 21 / 33,5 / 48 кПа.

    ⚠ ПРОВАЛОМ считается только ПРЕВЫШЕНИЕ верхней границы: оно означает, что нагрузка
    не длительная, и результат нельзя подписывать номинальным. Значение НИЖЕ полосы —
    не дефект расчёта, а свойство малой машины: у аутраннера Ø58 мм с неглубоким пазом
    книжные A = 35…65 кА/м при длительной плотности тока геометрически недостижимы
    (потребовался бы паз глубиной ~22 мм в статоре радиусом 22,5 мм). Такие машины
    выходят на «взрослое» σ только задиранием плотности тока и только кратковременно.
    """
    lo, mid, hi = TANGENTIAL_STRESS_PM
    s = float(sigma_pa)
    if s > hi:
        return Check("Касательное напряжение", FAIL,
                     "%.1f кПа выше верхней границы %.0f кПа для машин с ПМ" % (s / 1e3, hi / 1e3),
                     "Нагрузка не длительная: подписывать её номинальной нельзя. "
                     "Свериться с проверкой тепловой нагрузки AJ.")
    if s < lo:
        return Check("Касательное напряжение", PASS,
                     "%.1f кПа — ниже книжной полосы %.0f–%.0f (машина малая, паз неглубокий: "
                     "длительное σ этого класса ниже промышленного)"
                     % (s / 1e3, lo / 1e3, hi / 1e3))
    return Check("Касательное напряжение", PASS,
                 "%.1f кПа (норма ПМ %.0f–%.0f, среднее %.0f)"
                 % (s / 1e3, lo / 1e3, hi / 1e3, mid / 1e3))


def check_voltage_headroom(ke_phase_peak: float, speed_rpm: float, u_dc: float,
                           modulation: str = "svpwm") -> Check:
    """
    Влезает ли противо-ЭДС в шину. ФИЗИЧЕСКИ ОДНОЗНАЧНАЯ проверка — в отличие от сверки с
    паспортным kV, у которого конвенция неопределена (см. `machines/conventions.py`).
    Оценка СВЕРХУ: падения I·R и ω_э·L_s·I не учтены.
    """
    from magcore.fem2d.machines.conventions import max_speed_rpm, phase_voltage_limit

    v_max = phase_voltage_limit(u_dc, modulation)
    e = float(ke_phase_peak) * float(speed_rpm) / (60.0 / (2.0 * math.pi))
    n_max = max_speed_rpm(ke_phase_peak, u_dc, modulation)
    if e <= v_max:
        return Check("Запас по напряжению", PASS,
                     "ЭДС %.1f В при потолке %.1f В (макс. обороты %.0f)" % (e, v_max, n_max))
    return Check("Запас по напряжению", FAIL,
                 "ЭДС %.1f В при потолке %.1f В — заявленные %.0f об/мин недостижимы "
                 "(предел %.0f)" % (e, v_max, speed_rpm, n_max),
                 "Уменьшить витки в %.2f раза либо поднять напряжение шины." % (e / v_max))


def check_permeance_coefficient(pc: float, pc_min: float = 3.0) -> Check:
    """
    Коэффициент проницания P_c = B_op/(μ₀|H_op|). Для машин с ПОВЕРХНОСТНЫМИ магнитами
    типичен диапазон 4–6; ниже ~3 магнит сидит низко на нагрузочной линии и конструкция
    сама по себе склонна к размагничиванию — вывод о МАТЕРИАЛЕ на такой цепи не защитим.
    Жёсткий потолок задаёт геометрия: P_c ≤ h_магнита/зазор, всё остальное только уменьшает.
    """
    p = float(pc)
    if p >= pc_min:
        return Check("Коэффициент проницания", PASS, "P_c = %.2f (норма для SPM 4–6)" % p)
    return Check("Коэффициент проницания", FAIL,
                 "P_c = %.2f ниже порога %.1f (норма для SPM 4–6)" % (p, pc_min),
                 "Главный рычаг — ЗАЗОР (P_c ≤ h_магнита/зазор), затем толщина магнита; "
                 "зубцовые башмаки дают лишь ~+11 %. Иначе вывод получится о цепи, не о "
                 "материале — и сравнение SmCo/NdFeB надо вести при ОДИНАКОВОМ P_c.")


def check_magnet_model_range(T_magnet_max: float, T_limit: float) -> Check:
    """Не вышла ли температура магнита за область достоверности его модели."""
    if T_magnet_max < T_limit:
        return Check("Магнит в области достоверности модели", PASS,
                     "T_max %.0f °C < предела %.0f °C" % (T_magnet_max, T_limit))
    return Check("Магнит в области достоверности модели", FAIL,
                 "T_max %.0f °C ≥ предела модели %.0f °C" % (T_magnet_max, T_limit),
                 "За пределом кривая B(H,T) не определена — числам верить нельзя.")
