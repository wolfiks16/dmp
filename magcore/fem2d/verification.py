"""
БЛОК ПРОВЕРОК ДОСТОВЕРНОСТИ — результат выдаётся вместе с доказательством, что ему можно верить.

Зачем: правдоподобные, но НЕВЕРНЫЕ числа — самый опасный режим отказа. Реальные случаи,
на которых это выстрадано (`docs/solver_spec.md §5`):
  • итерация не сошлась, а поле «выглядит нормально» (ДП25: невязка застряла на 2.9e-2,
    поле отличалось от верного на единицы процентов — на глаз не отличить);
  • таблица B(H) оборвалась до насыщения ⇒ развал итерации (карта из 32 точек впустую);
  • зазор тоньше элемента сетки ⇒ поле в нём не разрешено;
  • грубый шаг по времени ⇒ траектория ошиблась на 51 °C.

Правило: **если проверка провалена — результат считать непригодным для отчёта**.
"""
from __future__ import annotations

import math
from dataclasses import dataclass, field

import numpy as np

from magcore.constants import MU0

PASS, FAIL, SKIP = "ok", "fail", "skip"


@dataclass(frozen=True, slots=True)
class Check:
    """Одна проверка: что проверяли, чем закончилось, что делать при провале."""

    name: str
    status: str            # PASS | FAIL | SKIP
    value: str             # человекочитаемый результат
    hint: str = ""         # как чинить (показывается при FAIL)

    @property
    def ok(self) -> bool:
        return self.status != FAIL


@dataclass(frozen=True, slots=True)
class VerificationReport:
    """Свод проверок расчёта."""

    checks: list = field(default_factory=list)

    @property
    def trustworthy(self) -> bool:
        """Ни одна проверка не провалена (пропущенные не считаются провалом)."""
        return all(c.ok for c in self.checks)

    @property
    def failed(self) -> list:
        return [c for c in self.checks if c.status == FAIL]

    def to_dict(self) -> dict:
        return {
            "trustworthy": self.trustworthy,
            "checks": [{"name": c.name, "status": c.status, "value": c.value, "hint": c.hint}
                       for c in self.checks],
            "summary": ("все проверки пройдены" if self.trustworthy else
                        "НЕ ПРОЙДЕНО: " + "; ".join(c.name for c in self.failed)),
        }


# ------------------------------------------------------------------ отдельные проверки

def check_convergence(converged: bool, n_iter: int, residual: float,
                      tol: float = 1.0e-6) -> Check:
    """Сошлась ли нелинейная итерация. Самая частая и самая незаметная проблема."""
    if converged:
        return Check("Сходимость нелинейной итерации", PASS,
                     "сошлось за %d итер., невязка %.1e" % (n_iter, residual))
    return Check(
        "Сходимость нелинейной итерации", FAIL,
        "НЕ сошлось за %d итер., невязка %.1e (нужно < %.0e)" % (n_iter, residual, tol),
        "Уменьшить релаксацию (при насыщенном железе до ω≈0.05), измельчить сетку в зазоре, "
        "проверить, доходит ли кривая B(H) до насыщения.")


def check_airgap_resolution(mesh, gap_cells_mask, gap_thickness: float,
                            min_elements: float = 3.0) -> Check:
    """
    Разрешён ли зазор сеткой. Если элемент толще зазора, поле в нём не считается —
    и итерация обычно разваливается (проверено на ДП25: зазор 0.268 мм при элементе 0.30 мм).
    """
    idx = np.where(np.asarray(gap_cells_mask, dtype=bool))[0]
    if idx.size == 0:
        return Check("Разрешение зазора", SKIP, "ячейки зазора не выделены")
    areas = np.array([mesh.cell_area(int(c)) for c in idx], dtype=float)
    h = math.sqrt(2.0 * float(np.mean(areas)))            # характерный размер треугольника
    n = float(gap_thickness) / h if h > 0 else 0.0
    if n >= min_elements:
        return Check("Разрешение зазора", PASS, "%.1f элемента поперёк (нужно ≥%.0f)" % (n, min_elements))
    return Check("Разрешение зазора", FAIL,
                 "%.1f элемента поперёк зазора %.3f мм (нужно ≥%.0f)"
                 % (n, gap_thickness * 1e3, min_elements),
                 "Измельчить сетку ИМЕННО в зазоре (mesh_size_by_region), а не всю модель.")


def check_steel_saturation(curves) -> Check:
    """
    Доходят ли таблицы B(H) до насыщения. Обрыв там, где сталь ещё магнитно активна,
    даёт скачок проницаемости на границе таблицы и разваливает решатель.
    """
    bad = []
    for c in curves:
        if c is None:
            continue
        dHdB = np.diff(c.H_values)[-1] / np.diff(c.B_values)[-1]
        mu_r_last = 1.0 / (dHdB * MU0)
        if mu_r_last >= 2.0 or c.B_values.max() < 2.0:
            bad.append("%s (μ_r на конце %.1f, B_max %.2f Тл)" % (c.name, mu_r_last, c.B_values.max()))
    if not bad:
        return Check("Кривые стали доходят до насыщения", PASS, "μ_r на конце таблиц → 1")
    return Check("Кривые стали доходят до насыщения", FAIL, "; ".join(bad),
                 "Продолжить таблицу B(H) до μ_r≈1 (обычно 2.1–2.2 Тл) физическим хвостом.")


def check_energy_balance(stored, loss_power, outflow, dt: float,
                         tol: float = 1.0e-9) -> Check:
    """
    Энергобаланс транзиента: d(запас)/dt = источник − отвод. Оракул связки:
    невязка должна быть на уровне машинной точности.
    """
    st = np.asarray(stored, dtype=float)
    lp = np.asarray(loss_power, dtype=float)
    of = np.asarray(outflow, dtype=float)
    if st.size < 3:
        return Check("Энергобаланс", SKIP, "мало шагов по времени")
    d = np.diff(st) / float(dt)
    err = float(np.max(np.abs(d[1:] - (lp[2:] - of[2:])) / np.maximum(np.abs(lp[2:]), 1.0)))
    if err < tol:
        return Check("Энергобаланс", PASS, "относит. невязка %.1e" % err)
    return Check("Энергобаланс", FAIL, "относит. невязка %.1e (норма < %.0e)" % (err, tol),
                 "Нарушен баланс запас/источник/отвод — ошибка в сборке тепловой задачи.")


def check_time_step(dt: float, dt_max: float = 0.5) -> Check:
    """
    Шаг по времени. Проверено: dt=5 с давал расхождение траектории 51 °C, dt≤0.5 с — 2.6 °C.
    Строгая проверка требует прогона с dt/2; здесь — быстрый предохранитель по величине.
    """
    if dt <= dt_max:
        return Check("Шаг по времени", PASS, "dt = %.2f с (≤ %.1f)" % (dt, dt_max))
    return Check("Шаг по времени", FAIL, "dt = %.2f с — грубо (нужно ≤ %.1f)" % (dt, dt_max),
                 "Уменьшить шаг: при грубом шаге траектория нагрева искажается "
                 "(проверено: 5 с давали ошибку 51 °C).")


def check_runaway_margin(s_actual: float, s_crit: float) -> Check:
    """Запас до теплового разгона: s < s_crit ⇒ стационар существует."""
    if s_crit <= 0:
        return Check("Запас до теплового разгона", SKIP, "порог не вычислен")
    ratio = float(s_actual) / float(s_crit)
    if ratio < 1.0:
        return Check("Запас до теплового разгона", PASS,
                     "s = %.2f·s_crit (стационар существует)" % ratio)
    return Check("Запас до теплового разгона", FAIL,
                 "s = %.2f·s_crit — режим за порогом" % ratio,
                 "Это не ошибка расчёта, а результат: охлаждение не догоняет тепловыделение. "
                 "Снизить ток или улучшить охлаждение.")


