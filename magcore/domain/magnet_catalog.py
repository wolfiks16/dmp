_BY_ID: dict[str, MagnetGrade] = {g.id: g for g in CATALOG}


def by_id(grade_id: str) -> MagnetGrade:
    try:
        return _BY_ID[grade_id]
    except KeyError:
        raise KeyError("нет марки %r в каталоге (%d марок)" % (grade_id, len(CATALOG))) from None


def find(query: str | None = None, family: str | None = None,
         source: str | None = None) -> list[MagnetGrade]:
    """
    Поиск по каталогу: подстрока в марке (регистронезависимо, кириллица и латиница),
    фильтр по семейству ("NdFeB"/"SmCo") и по источнику. Порядок — как в каталоге.
    """
    if family is not None and family not in FAMILIES:
        raise ValueError("семейство должно быть одним из %s" % (FAMILIES,))
    q = (query or "").strip().lower()
    out = []
    for g in CATALOG:
        if family is not None and g.family != family:
            continue
        if source is not None and g.source != source:
            continue
        if q and q not in g.grade.lower() and q not in g.id.lower():
            continue
        out.append(g)
    return out


def families_summary() -> dict[str, int]:
    """Сколько марок в каждом семействе — для группировки в интерфейсе."""
    return {f: sum(1 for g in CATALOG if g.family == f) for f in FAMILIES}


def to_magnet(grade_id: str, easy_axis=(1.0, 0.0, 0.0), *, hk: float | None = None,
              T0: float = 20.0) -> AnisotropicBHTMagnet:
    """
    Построить модель B(H,T) по марке каталога.

    `hk` — реальное поле колена [А/м], если оно известно из измеренной кривой; иначе
    берётся допущение HK_RATIO*H_cJ (см. шапку модуля). Подставлять измеренное значение
    настоятельно рекомендуется: именно колено определяет запас до необратимой потери.
    """
    g = by_id(grade_id)
    return magnet_from_datasheet(
        g.id, "%s (%s)" % (g.grade, g.source_title), easy_axis,
        Br=g.Br, Hcb=g.Hcb, Hk=float(hk) if hk is not None else g.Hk, Hcj=g.Hcj,
        alpha_Br=g.alpha_Br, gamma_Hc=g.gamma_Hc, T0=T0,
    )
