@dataclass(frozen=True, slots=True)
class MagnetGrade:
    """Марка магнита из справочника. Все величины в СИ."""

    id: str                  # машинный идентификатор (латиница)
    grade: str               # марка как в справочнике
    family: str              # "NdFeB" | "SmCo"
    source: str              # ключ SOURCES
    Br: float                # остаточная индукция [Тл]
    Hcb: float               # коэрцитивная сила по индукции [А/м]
    Hcj: float               # коэрцитивная сила по намагниченности [А/м]
    BHmax: float | None      # максимальное энергетическое произведение [кДж/м³]
    alpha_Br: float          # темп. коэффициент B_r, %/°C (положительный = падение)
    gamma_Hc: float          # темп. коэффициент H_cJ и колена, %/°C (положительный = падение)
    T_max: float | None      # максимальная рабочая температура [°C]
    note: str = ""

    @property
    def hk_ratio(self) -> float:
        """Принятое отношение H_k/H_cJ для семейства марки."""
        return HK_RATIO.get(self.family, HK_RATIO_DEFAULT)

    @property
    def Hk(self) -> float:
        """Поле колена [А/м] — ДОПУЩЕНИЕ hk_ratio*H_cJ (в справочниках не приводится)."""
        return self.hk_ratio * self.Hcj

    @property
    def source_title(self) -> str:
        return SOURCES.get(self.source, self.source)

    def as_dict(self) -> dict:
        return dict(id=self.id, grade=self.grade, family=self.family, source=self.source,
                    source_title=self.source_title, Br=self.Br, Hcb=self.Hcb, Hcj=self.Hcj,
                    Hk=self.Hk, hk_ratio=self.hk_ratio, BHmax=self.BHmax, alpha_Br=self.alpha_Br,
                    gamma_Hc=self.gamma_Hc, T_max=self.T_max, note=self.note)


