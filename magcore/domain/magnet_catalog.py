# H_k = HK_RATIO[семейство] * H_cJ — ДОПУЩЕНИЕ (в справочниках колено не приводится).
# Коэффициент РАЗНЫЙ по семействам: у NdFeB петля прямоугольнее (колено ближе к H_cJ),
# у Sm-Co спад более пологий (Sergey, 2026-08-27). Чем ВЫШЕ коэффициент, тем ДАЛЬШЕ
# колено от рабочей точки, то есть тем БОЛЬШЕ расчётный запас до необратимой потери.
HK_RATIO: dict[str, float] = {"NdFeB": 0.95, "SmCo": 0.85}
