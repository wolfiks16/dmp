def _set_run_font(run, size=14, bold=False, italic=False, color=None):
    run.font.name = FONT
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.italic = italic
    if color is not None:
        run.font.color.rgb = color
    rpr = run._element.get_or_add_rPr()
    rfonts = rpr.find(qn("w:rFonts"))
    if rfonts is None:
        rfonts = OxmlElement("w:rFonts"); rpr.append(rfonts)
    for a in ("w:ascii", "w:hAnsi", "w:cs", "w:eastAsia"):
        rfonts.set(qn(a), FONT)


def body(doc, text, size=14, justify=True, indent=True, italic=False, bold=False,
         after=6, before=0):
    p = doc.add_paragraph(); pf = p.paragraph_format
    pf.line_spacing = 1.5; pf.space_after = Pt(after); pf.space_before = Pt(before)
    pf.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY if justify else WD_ALIGN_PARAGRAPH.LEFT
    if indent:
        pf.first_line_indent = Cm(1.25)
    _set_run_font(p.add_run(text), size=size, italic=italic, bold=bold)
    return p


def heading(doc, text, size=14, before=12, after=6, center=False):
    p = doc.add_paragraph(); pf = p.paragraph_format
    pf.line_spacing = 1.5; pf.space_before = Pt(before); pf.space_after = Pt(after)
    pf.keep_with_next = True
    pf.alignment = WD_ALIGN_PARAGRAPH.CENTER if center else WD_ALIGN_PARAGRAPH.LEFT
    _set_run_font(p.add_run(text), size=size, bold=True)
    return p


def run_para(doc, segments, after=6, before=0, indent=True, justify=True):
    """Абзац из нескольких ранов: segments = [(text, {bold,italic,size}), ...]."""
    p = doc.add_paragraph(); pf = p.paragraph_format
    pf.line_spacing = 1.5; pf.space_after = Pt(after); pf.space_before = Pt(before)
    pf.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY if justify else WD_ALIGN_PARAGRAPH.LEFT
    if indent:
        pf.first_line_indent = Cm(1.25)
    for txt, opt in segments:
        _set_run_font(p.add_run(txt), size=opt.get("size", 14),
                      bold=opt.get("bold", False), italic=opt.get("italic", False))
    return p


def bullet(doc, text, size=14):
    p = doc.add_paragraph(style="List Bullet"); pf = p.paragraph_format
    pf.line_spacing = 1.5; pf.space_after = Pt(3); pf.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    _set_run_font(p.add_run(text), size=size)
    return p


def _shade(cell, fill):
    tcpr = cell._tc.get_or_add_tcPr(); shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear"); shd.set(qn("w:color"), "auto"); shd.set(qn("w:fill"), fill)
    tcpr.append(shd)


def _cell(cell, text, size=10, bold=False, fill=None, align="left"):
    if fill:
        _shade(cell, fill)
    cell.vertical_alignment = 1
    p = cell.paragraphs[0]; pf = p.paragraph_format
    pf.line_spacing = 1.0; pf.space_after = Pt(1); pf.space_before = Pt(1)
    pf.first_line_indent = Cm(0)
    pf.alignment = {"left": WD_ALIGN_PARAGRAPH.LEFT, "center": WD_ALIGN_PARAGRAPH.CENTER}[align]
    _set_run_font(p.add_run(text), size=size, bold=bold)


def table(doc, headers, rows, widths_cm, font=10):
    t = doc.add_table(rows=1, cols=len(headers)); t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER; t.autofit = False
    for j, h in enumerate(headers):
        _cell(t.rows[0].cells[j], h, size=font, bold=True, fill="D9E2F3", align="center")
    for row in rows:
        cells = t.add_row().cells
        for j, val in enumerate(row):
            _cell(cells[j], val, size=font, align="left")
    for j, w in enumerate(widths_cm):
        for r in t.rows:
            r.cells[j].width = Cm(w)
    return t


def caption(doc, text):
    p = doc.add_paragraph(); pf = p.paragraph_format
    pf.line_spacing = 1.0; pf.space_before = Pt(8); pf.space_after = Pt(3)
    pf.keep_with_next = True
    _set_run_font(p.add_run(text), size=12, italic=True)


def add_page_numbers(section):
    p = section.footer.paragraphs[0]; p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run(); _set_run_font(run, size=11)
    a = OxmlElement("w:fldChar"); a.set(qn("w:fldCharType"), "begin")
    b = OxmlElement("w:instrText"); b.set(qn("xml:space"), "preserve"); b.text = "PAGE"
    c = OxmlElement("w:fldChar"); c.set(qn("w:fldCharType"), "end")
    run._element.append(a); run._element.append(b); run._element.append(c)


